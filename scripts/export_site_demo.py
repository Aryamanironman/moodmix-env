"""Export license-free showcase transitions for the static Vercel site.

The commercial 20-song crate stays local.  These renders use the synthesized
demo tracks (generated by scripts/make_demo_library.py), so they can be hosted
publicly.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

import numpy as np
from stable_baselines3 import PPO

from moodmix_env.env_v1 import MoodMixV1Env
from moodmix_env.expert_v1 import expert_action
from moodmix_env.render_v2 import render_transition
from moodmix_env.select_v1 import best_cues

DATA = ROOT / "data" / "demo"
OUT = ROOT / "site" / "demo"
MODEL = ROOT / "models" / "ppo_v1_final.zip"

SHOWS = [
    ("energetic_pulse", "party_strobe", "model"),
    ("party_strobe", "energetic_pulse", "model"),
    ("happy_bounce", "energetic_pulse", "model"),
]


def summary(track: dict) -> dict:
    return {
        "id": track["id"], "bpm": track["bpm"], "key": track["key"],
        "mode": track["mode"], "mood": track["mood"],
        "duration": track["duration"],
        "cues": [{"beat": c["beat"], "bar": c["bar"],
                  "section": c["section"], "energy": c["energy"]}
                 for c in track["cues"]],
    }


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    model = PPO.load(str(MODEL), device="cpu")
    transitions = []
    for index, (a, b, kind) in enumerate(SHOWS, 1):
        env = MoodMixV1Env(data_dir=DATA, max_steps=32)
        if kind == "model":
            def policy(obs, _env=env):
                action, _ = model.predict(obs, deterministic=True)
                return action
        else:
            def policy(obs, _env=env):
                return expert_action(_env)

        picked = best_cues(env, policy, a, b, seed=0)
        env = MoodMixV1Env(data_dir=DATA, max_steps=32)
        obs, _ = env.reset(seed=0, options={"track_a": a, "track_b": b,
                                            "cue_a": picked["cue_a"],
                                            "cue_b": picked["cue_b"]})
        steps = []
        while True:
            action = policy(obs)
            obs, reward, terminated, truncated, _ = env.step(action)
            frame = env.trace[-1]
            action = frame["action"]
            steps.append({
                "step": env.step_count,
                "beat_a": frame["beat_a"], "beat_b": frame["beat_b"],
                "fader": float(action[0]),
                "eq_a": [float(v) for v in action[1:4]],
                "eq_b": [float(v) for v in action[4:7]],
                "filter": float(action[7]),
                "gain_a": float(frame["gain_a"]),
                "gain_b": float(frame["gain_b"]),
                "bands_a": [float(v) for v in frame["bands_a"]],
                "bands_b": [float(v) for v in frame["bands_b"]],
                "mix_a": [float(v) for v in frame["mix_a"]],
                "mix_b": [float(v) for v in frame["mix_b"]],
                "level": float(frame["level"]),
                "level_smooth": float(frame["level_smooth"]),
                "low_overlap": float(frame["low_overlap"]),
                "blend": float(frame["blend"]),
                "target": float(frame["target"]),
                "shape": float(frame["shape"]),
                "jump": float(frame["jump"]),
                "section_a": env._section(env.track_a, int(frame["beat_a"])),
                "section_b": env._section(env.track_b, int(frame["beat_b"])),
            })
            if terminated or truncated:
                break
        beats = env.track_a["beat_times"]
        relative = (beats[env.cue_a:env.cue_a + env.step_count + 1]
                    - beats[env.cue_a]).tolist()
        wav = f"demo/{index:02d}_{a}__{b}__{kind}.wav"
        render_transition(env, ROOT / "site" / wav)
        transitions.append({
            "id": f"{index:02d}_{a}__{b}__{kind}",
            "label": f"{a.replace('_', ' ').title()} → {b.replace('_', ' ').title()}",
            "policy": kind,
            "track_a": summary(env.track_a),
            "track_b": summary(env.track_b),
            "cue_a": int(env.cue_a), "cue_b": int(env.cue_b),
            "steps": steps,
            "beat_times": relative,
            "beat_seconds": 60.0 / float(env.track_a["bpm"]),
            "duration": float(relative[-1]) if relative else 0.0,
            "reward": float(sum(env.episode_components.values())),
            "components": {k: float(v)
                           for k, v in env.episode_components.items()},
            "final_fader": float(env.fader),
            "mean_level_jump": float(np.mean(env._level_jumps))
            if env._level_jumps else 0.0,
            "mean_low_overlap": float(np.mean(env._low_overlaps))
            if env._low_overlaps else 0.0,
            "audio_url": wav,
        })
        print(f"{index}. {a} -> {b} [{kind}]  reward {transitions[-1]['reward']:+.2f}  "
              f"cues {env.cue_a}/{env.cue_b}  {wav}", flush=True)

    (OUT / "transitions.json").write_text(
        json.dumps({"transitions": transitions}, indent=1), encoding="utf-8")
    print(f"wrote {OUT / 'transitions.json'}")


if __name__ == "__main__":
    main()
